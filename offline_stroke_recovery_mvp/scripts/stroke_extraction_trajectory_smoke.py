def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--repo",
        type=Path,
        default=Path("external_repos") / "StrokeExtraction",
        help="Path to the external StrokeExtraction checkout.",
    )
    parser.add_argument(
        "--dataset-dir",
        type=Path,
        default=DEFAULT_DATASET_DIR,
        help="Path to the limited intermediate dataset generated by the SDNet smoke.",
    )
    parser.add_argument(
        "--segnet-checkpoint",
        type=Path,
        default=DEFAULT_SEGNET_CHECKPOINT,
        help="Path to the SegNet smoke checkpoint.",
    )
    parser.add_argument(
        "--extractnet-checkpoint",
        type=Path,
        default=DEFAULT_EXTRACTNET_CHECKPOINT,
        help="Path to the ExtractNet smoke checkpoint.",
    )
    parser.add_argument("--batch-size", type=int, default=2)
    parser.add_argument("--max-steps", type=int, default=2)
    parser.add_argument("--samples-per-split", type=int, default=2)
    parser.add_argument("--mask-quantile", type=float, default=0.7)
    parser.add_argument("--learning-rate", type=float, default=0.0001)
    parser.add_argument("--seed", type=int, default=123)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument(
        "--report",
        type=Path,
        default=None,
        help="JSON report path. Defaults to <output-dir>/trajectory_smoke_report.json.",
    )
    return parser


def write_report(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> int:
    args = build_arg_parser().parse_args()
    payload = run_trajectory_smoke(
        args.repo,
        dataset_dir=args.dataset_dir,
        segnet_checkpoint=args.segnet_checkpoint,
        extractnet_checkpoint=args.extractnet_checkpoint,
        output_dir=args.output_dir,
        batch_size=args.batch_size,
        max_steps=args.max_steps,
        samples_per_split=args.samples_per_split,
        mask_quantile=args.mask_quantile,
        learning_rate=args.learning_rate,
        seed=args.seed,
    )
    report_path = args.report or (args.output_dir / "trajectory_smoke_report.json")
    write_report(report_path, payload)
    print(json.dumps(payload, ensure_ascii=False, indent=2))
    return 0 if payload["status"] == "ok" else 1


def run_trajectory_smoke(
    repo_dir: Path,
    *,
    dataset_dir: Path,
    segnet_checkpoint: Path,
    extractnet_checkpoint: Path,
    output_dir: Path,
    batch_size: int,
    max_steps: int,
    samples_per_split: int,
    learning_rate: float,
    seed: int,
    mask_quantile: float = 0.7,
) -> dict[str, Any]:
    stage = "trajectory_recovery_smoke"
    repo_dir = Path(repo_dir)
    dataset_dir = Path(dataset_dir)
    segnet_checkpoint = Path(segnet_checkpoint)
    extractnet_checkpoint = Path(extractnet_checkpoint)
    output_dir = Path(output_dir)
    required_paths = [
        repo_dir,
        repo_dir / "model",
        dataset_dir,
        dataset_dir / "train",
        dataset_dir / "test",
        segnet_checkpoint,
        extractnet_checkpoint,
    ]
    missing = [str(path) for path in required_paths if not path.exists()]
    if missing:
        return {"status": "missing_required_paths", "stage": stage, "missing": missing}

    if not _is_within_output_root(output_dir, DEFAULT_ALLOWED_OUTPUT_ROOT):
        return {
            "status": "invalid_output_dir",
            "stage": stage,
            "output_dir": str(output_dir),
            "allowed_root": str(DEFAULT_ALLOWED_OUTPUT_ROOT),
        }

    if (
        batch_size <= 0
        or max_steps <= 0
        or samples_per_split <= 0
        or learning_rate <= 0
        or mask_quantile <= 0
        or mask_quantile >= 1
    ):
        return {
            "status": "invalid_args",
            "stage": stage,
            "args": {
                "batch_size": batch_size,
                "max_steps": max_steps,
                "samples_per_split": samples_per_split,
                "mask_quantile": mask_quantile,
                "learning_rate": learning_rate,
            },
        }

    missing_modules = find_missing_modules(["torch", "torchvision", "scipy", "pandas", "matplotlib", "cv2"])
    if missing_modules:
        return {
            "status": "missing_python_dependencies",
            "stage": stage,
            "missing_modules": missing_modules,
        }

    import torch
    from torchvision.transforms import Resize

    import numpy as np_local

    if not hasattr(np_local, "float"):
        np_local.float = float  # type: ignore[attr-defined]
    if not hasattr(np_local, "int"):
        np_local.int = int  # type: ignore[attr-defined]

    if str(repo_dir) not in sys.path:
        sys.path.insert(0, str(repo_dir))
    if not torch.cuda.is_available():
        return {"status": "cuda_unavailable", "stage": stage, "environment": _environment(torch)}

    from load_data_for_SegNetExtractNet import SegNetExtractNetLoader
    from model.model_of_ExtractNet import ExtractNet
    from model.model_of_SegNet import SegNet

    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)

    device = torch.device("cuda")
    torch.backends.cudnn.benchmark = True

    train_dataset = SegNetExtractNetLoader(is_training=True, dataset_path=str(dataset_dir), is_single=True)
    test_dataset = SegNetExtractNetLoader(is_training=False, dataset_path=str(dataset_dir), is_single=True)
    train_samples = [train_dataset[i] for i in range(len(train_dataset))]
    test_samples = [test_dataset[i] for i in range(len(test_dataset))]
    if not train_samples or not test_samples:
        return {
            "status": "no_dataset_samples",
            "stage": stage,
            "dataset": {
                "path": str(dataset_dir),
                "train_sample_count": len(train_samples),
                "test_sample_count": len(test_samples),
            },
        }

    output_dir.mkdir(parents=True, exist_ok=True)
    predicted_mask_dir = output_dir / "predicted_masks"
    recovery_batch_dir = output_dir / "recovery_batch"
    metadata_dir = output_dir / "metadata"
    predicted_mask_dir.mkdir(parents=True, exist_ok=True)
    recovery_batch_dir.mkdir(parents=True, exist_ok=True)
    metadata_dir.mkdir(parents=True, exist_ok=True)

    seg_net = SegNet(out_feature=True).to(device)
    seg_state = torch.load(segnet_checkpoint, map_location=device)
    seg_net.load_state_dict(seg_state["net"])
    seg_net.eval().requires_grad_(False)

    extract_net = ExtractNet().to(device)
    extract_state = torch.load(extractnet_checkpoint, map_location=device)
    extract_net.load_state_dict(extract_state["net"])
    extract_net.eval().requires_grad_(False)

    resize = Resize([256, 256])
    sample_plan = plan_trajectory_samples(
        train_count=len(train_samples),
        test_count=len(test_samples),
        samples_per_split=samples_per_split,
        max_steps=max_steps,
    )
    if not sample_plan:
        return {
            "status": "no_samples_planned",
            "stage": stage,
            "dataset": {
                "path": str(dataset_dir),
                "train_sample_count": len(train_samples),
                "test_sample_count": len(test_samples),
            },
        }

    torch.cuda.empty_cache()
    torch.cuda.reset_peak_memory_stats()
    start = time.perf_counter()
    records: list[dict[str, Any]] = []

    sample_lookup = {
        "train": train_samples,
        "test": test_samples,
    }
    with torch.no_grad():
        for split_name, split_index in sample_plan:
            sample = sample_lookup[split_name][split_index - 1]
            record = _recover_sample(
                split_name,
                split_index,
                sample,
                seg_net=seg_net,
                extract_net=extract_net,
                device=device,
                resize=resize,
                predicted_mask_dir=predicted_mask_dir,
                recovery_batch_dir=recovery_batch_dir,
                mask_quantile=mask_quantile,
            )
            records.append(record)

    manual_audit_sheet_path = write_manual_audit_sheet(recovery_batch_dir)
    batch_rows = [_batch_row_for_report(record) for record in records]
    batch_report_path = recovery_batch_dir / "batch_report.md"
    write_batch_report(batch_report_path, batch_rows, manual_audit_sheet_path=manual_audit_sheet_path)

    metadata_path = metadata_dir / "trajectory_smoke_metadata.json"
    write_report(
        metadata_path,
        {
            "source": "stroke_extraction_trajectory_smoke",
            "dataset": str(dataset_dir),
            "samples": records,
            "sample_plan": sample_plan,
            "manual_audit_sheet_path": str(manual_audit_sheet_path),
            "batch_report_path": str(batch_report_path),
        },
    )

    status = "ok" if records else "no_samples_completed"
    return {
        "status": status,
        "stage": stage,
        "environment": _environment(torch),
        "dataset": {
            "path": str(dataset_dir),
            "train_sample_count": len(train_samples),
            "test_sample_count": len(test_samples),
        },
        "args": {
            "batch_size": batch_size,
            "max_steps": max_steps,
            "samples_per_split": samples_per_split,
            "mask_quantile": mask_quantile,
            "learning_rate": learning_rate,
            "seed": seed,
        },
        "completed_samples": len(records),
        "total_seconds": round(time.perf_counter() - start, 4),
        "max_memory_allocated_mib": _max_memory_mib(torch),
        "segnet_checkpoint_path": str(segnet_checkpoint),
        "extractnet_checkpoint_path": str(extractnet_checkpoint),
        "predicted_mask_dir": str(predicted_mask_dir),
        "recovery_batch_dir": str(recovery_batch_dir),
        "manual_audit_sheet_path": str(manual_audit_sheet_path),
        "batch_report_path": str(batch_report_path),
        "metadata_path": str(metadata_path),
        "sample_plan": sample_plan,
        "samples": records,
    }


def _recover_sample(
    split_name: str,
    split_index: int,
    sample: dict[str, Any],
    *,
    seg_net: Any,
    extract_net: Any,
    device: Any,
    resize: Any,
    predicted_mask_dir: Path,
    recovery_batch_dir: Path,
    mask_quantile: float,
) -> dict[str, Any]:
    import torch

    batch = _prepare_extract_batch(sample, seg_net=seg_net, device=device, resize=resize)
    extract_out = extract_net(batch[1], batch[3], batch[2], batch[0], batch[4])
    extract_prob = torch.sigmoid(extract_out).detach()
    prediction_threshold = float(torch.quantile(extract_prob, mask_quantile).cpu())
    extract_result = extract_prob >= prediction_threshold
    restored_extract, restored_label = _restore_strokes(extract_result, batch[5], batch[6])
    mask_shape = restored_label[0].shape if restored_label else tuple(batch[5].shape[-2:])
    predicted_mask = refine_predicted_mask(
        combine_predicted_masks(restored_extract, shape=mask_shape),
        min_component_pixels=20,
    )
    sample_name = f"{split_name}_{split_index}"
    predicted_mask_path = predicted_mask_dir / f"{sample_name}_union.png"
    save_binary_mask_png(predicted_mask_path, predicted_mask)

    sample_dir = run_single_image(predicted_mask_path, recovery_batch_dir)
    summary_path = sample_dir / "recovery_summary.json"
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    return {
        "split": split_name,
        "split_index": split_index,
        "sample_name": sample_name,
        "predicted_mask_path": str(predicted_mask_path),
        "predicted_foreground_pixel_count": int(np.asarray(predicted_mask, dtype=bool).sum()),
        "prediction_threshold": prediction_threshold,
        "mask_quantile": mask_quantile,
        "restored_stroke_count": len(restored_extract),
        "sample_dir": str(sample_dir),
        "summary_path": str(summary_path),
        "trajectory_path": str(sample_dir / "trial_ordered_trajectory.csv"),
        "final_trajectory_image": str(sample_dir / "final_trajectory.png"),
        "status": summary.get("status", ""),
        "audit_status": summary.get("audit_status", ""),
        "failure_reason": summary.get("failure_reason", "n/a"),
        "component_count": summary.get("component_count", "n/a"),
        "branch_point_count": summary.get("branch_point_count", "n/a"),
        "max_pen_up_jump_px": summary.get("max_pen_up_jump_px", "n/a"),
        "trajectory_point_count": summary.get("trajectory_point_count", "n/a"),
    }


def combine_predicted_masks(masks: Iterable[Any], *, shape: tuple[int, int] | None = None) -> np.ndarray:
    mask_list = [np.asarray(mask, dtype=bool) for mask in masks]
    if not mask_list:
        if shape is None:
            raise ValueError("shape is required when masks is empty")
        return np.zeros(shape, dtype=bool)
    combined_shape = shape or mask_list[0].shape
    combined = np.zeros(combined_shape, dtype=bool)
    for mask in mask_list:
        combined |= np.asarray(mask, dtype=bool)
    return combined


def save_binary_mask_png(path: Path, mask: Any) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    pixels = np.where(np.asarray(mask, dtype=bool), 0, 255).astype(np.uint8)
    Image.fromarray(pixels, mode="L").save(path)


def refine_predicted_mask(mask: Any, *, min_component_pixels: int) -> np.ndarray:
    filtered = _remove_border_touching_components(np.asarray(mask, dtype=bool))
    if not np.any(filtered):
        filtered = np.asarray(mask, dtype=bool)
    cleaned, _ = remove_small_components(filtered, min_component_pixels=min_component_pixels)
    return cleaned


def _remove_border_touching_components(mask: np.ndarray) -> np.ndarray:
    import cv2

    mask_u8 = np.asarray(mask, dtype=np.uint8)
    if mask_u8.ndim != 2:
        raise ValueError("mask must be a 2D array")
    count, labels, stats, _ = cv2.connectedComponentsWithStats(mask_u8, connectivity=8)
    filtered = np.zeros_like(mask_u8, dtype=bool)
    height, width = mask_u8.shape
    for label in range(1, count):
        left, top, component_width, component_height, _ = stats[label]
        touches_border = (
            left == 0
            or top == 0
            or left + component_width == width
            or top + component_height == height
        )
        if not touches_border:
            filtered[labels == label] = True
    return filtered


def plan_trajectory_samples(
    *,
    train_count: int,
    test_count: int,
    samples_per_split: int,
    max_steps: int,
) -> list[tuple[str, int]]:
    train_limit = min(train_count, samples_per_split)
    test_limit = min(test_count, samples_per_split)
    plan: list[tuple[str, int]] = []
    for sample_index in range(1, samples_per_split + 1):
        if len(plan) >= max_steps:
            break
        if sample_index <= train_limit:
            plan.append(("train", sample_index))
        if len(plan) >= max_steps:
            break
        if sample_index <= test_limit:
            plan.append(("test", sample_index))
        if len(plan) >= max_steps:
            break
    return plan


def _batch_row_for_report(record: dict[str, Any]) -> dict[str, Any]:
    return {
        "sample": f"{record['split']}_{record['split_index']}",
        "status": record.get("status", ""),
        "failure_reason": record.get("failure_reason", "n/a"),
        "audit_status": record.get("audit_status", ""),
        "component_count": record.get("component_count", "n/a"),
        "branch_point_count": record.get("branch_point_count", "n/a"),
        "max_pen_up_jump_px": record.get("max_pen_up_jump_px", "n/a"),
        "trajectory_point_count": record.get("trajectory_point_count", "n/a"),
        "sample_dir": record.get("sample_dir", "n/a"),
        "summary_path": record.get("summary_path", "n/a"),
        "trajectory_path": record.get("trajectory_path", "n/a"),
        "final_trajectory_image": record.get("final_trajectory_image", "n/a"),
    }


def _environment(torch_module: Any) -> dict[str, Any]:
    return {
        "torch_version": torch_module.__version__,
        "cuda_available": torch_module.cuda.is_available(),
        "device_name": torch_module.cuda.get_device_name(0) if torch_module.cuda.is_available() else "",
        "cuda_runtime": getattr(torch_module.version, "cuda", None),
    }


def _max_memory_mib(torch_module: Any) -> int:
    return int(round(torch_module.cuda.max_memory_allocated() / 1024 / 1024))


def _is_within_output_root(path: Path, root: Path) -> bool:
    path_parts = Path(path).parts
    root_parts = Path(root).parts
    return len(path_parts) >= len(root_parts) and path_parts[: len(root_parts)] == root_parts


def find_missing_modules(module_names: list[str]) -> list[str]:
    missing: list[str] = []
    for module_name in module_names:
        try:
            importlib.import_module(module_name)
        except ModuleNotFoundError:
            missing.append(module_name)
    return missing


